#!/bin/bash

# ===================================================================
#       🔬 经典SVD对照实验评估套件 (Classic SVD Control) 🔬
#
#  本脚本将为多个随机种子自动执行完整的“经典SVD对照实验”，
#  包括模型生成和评估，以验证我们的维度匹配方法的必要性。
# ===================================================================

# --- 配置 ---
# 在此数组中添加或修改你想要验证的种子
# 建议在所有三个种子上都运行，以获得完整的图像
SEEDS_TO_PROCESS=(42 123 456)

# 定义本次实验的新策略
STRATEGIES=('classic_svd_top' 'classic_svd_bottom')
K_VALUES=({1..10})
DATA_DIR="data/simple_graph/composition_90"

# 设置脚本在遇到任何错误时立即退出
set -e

# --- 主循环: 遍历所有需要验证的种子 ---
for seed in "${SEEDS_TO_PROCESS[@]}"; do
    echo ""
    echo "================================================================="
    echo "      🔬 开始处理经典SVD对照实验 (Seed): $seed 🔬"
    echo "================================================================="
    
    # --- 阶段 1: 为当前种子生成全部20个对照模型 ---
    echo ""
    echo "--- [阶段 1/2] 正在为 Seed $seed 生成对照模型... ---"
    # 注意：这里调用的是我们新写的Python脚本
    python run_classic_svd_control.py --seed "$seed"
    echo "--- ✅ Seed $seed 的对照模型生成完毕 ---"
    echo ""

    # --- 阶段 2: 评估刚刚为当前种子生成的所有模型 ---
    echo "--- [阶段 2/2] 正在评估 Seed $seed 的所有对照模型... ---"
    for strategy in "${STRATEGIES[@]}"; do
        echo ""
        echo "-------------------------------------------------"
        echo "📊 开始评估策略 (Seed $seed): $strategy"
        echo "-------------------------------------------------"
        for k in "${K_VALUES[@]}"; do
            # 文件名会自动匹配新策略名
            MODEL_FILE="hybrid_model_seed${seed}_${strategy}_k${k}.pt"
            
            echo ""
            echo "--- 评估 k=$k ---"
            
            if [ -f "$MODEL_FILE" ]; then
                python evaluate_hybrid_model.py --model_path "${MODEL_FILE}" --data_dir "${DATA_DIR}"
            else
                echo "🚨 错误: 未找到模型文件 ${MODEL_FILE}，跳过评估。"
                echo "🚨 请检查阶段1的生成过程是否出错。"
            fi
        done
    done
    echo ""
    echo "================================================================="
    echo "      🎉 Seed $seed 的全部对照评估任务均已成功执行完毕！ 🎉"
    echo "================================================================="
    echo ""
done

echo ""
echo "================================================================="
echo "      🎉🎉🎉 所有经典SVD对照实验均已成功执行完毕！ 🎉🎉🎉"
echo "================================================================="
echo "请整理数据，将结果与之前基于维度匹配的实验结果进行对比。"